const STANDARD_MERIDIAN = 120;

export function lookupLongitude(place?: string): number | undefined {
  if (!place) return undefined;
  for (const [city, lon] of Object.entries(CITY_LONGITUDE)) {
    if (place.includes(city.replace(/市$/, ""))) return lon;
  }
  for (const [prov, lon] of Object.entries(PROVINCE_LONGITUDE)) {
    if (place.includes(prov)) return lon;
  }
  return undefined;
}

/** 相对东经 120° 的真太阳时修正（分钟）。东边为正。 */
export function trueSolarOffsetMinutes(longitude: number): number {
  return Math.round((longitude - STANDARD_MERIDIAN) * 4);
}
